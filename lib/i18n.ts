// KID-403: the Help Center client island only renders help.* chrome copy, so it
// receives just this slice per language instead of two full dictionaries —
// typed against the EN source, so a missing key is a compile error.
export type HelpCopy = typeof en.help;

export const dictionaries: Record<Locale, Dict> = { en, ar };

export const helpCopy: Record<Locale, HelpCopy> = { en: en.help, ar: ar.help };

const MISSING_MARKER = "MISSING:";

export function localeOf(v: unknown): Locale {
  if (v === "ar" || v === "en") return v;
  return DEFAULT_LOCALE;
}

export function getDictionary(locale: Locale): Dict {
  return dictionaries[localeOf(locale)];
}

export function dirFor(locale: Locale): "ltr" | "rtl" {
  return locale === "ar" ? "rtl" : "ltr";
}

function lookup(dict: Dict, path: string[]): string {
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  let node: any = dict;
  for (const segment of path) {
    if (node === null || typeof node !== "object") return "";
    node = node[segment];
  }
  return typeof node === "string" ? node : "";
}

export function tr(dict: Dict, key: string, vars?: Record<string, string | number>): string {
  const path = key.split(".");
  let value = lookup(dict, path);
  if (value === "") {
    if (dict === dictionaries[DEFAULT_LOCALE]) value = key;
    else value = `${MISSING_MARKER}${key}`;
  }
  if (vars) {
    for (const [name, val] of Object.entries(vars)) {
      value = value.replaceAll(`{${name}}`, String(val));
    }
  }
  return value;
}

// Dot-path list of every leaf key (used by coverage checks/tests).
export function keysOf(enDict: Dict, prefix = ""): string[] {
  const out: string[] = [];
  for (const [k, v] of Object.entries(enDict as Record<string, unknown>)) {
    const key = prefix ? `${prefix}.${k}` : k;
    if (v !== null && typeof v === "object") out.push(...keysOf(v as Dict, key));
    else out.push(key);
  }
  return out;
}

